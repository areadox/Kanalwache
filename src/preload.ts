import { contextBridge, ipcRenderer } from 'electron';

contextBridge.exposeInMainWorld('kanalwache', {
  getState: () => ipcRenderer.invoke('get-state'),
  onState: (cb: (s: unknown) => void) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onOpenChannel: (cb: (p: unknown) => void) => ipcRenderer.on('open-channel', (_e, p) => cb(p)),
  onChannelOffline: (cb: (login: string) => void) => ipcRenderer.on('channel-offline', (_e, l) => cb(l)),
  addChannel: (login: string) => ipcRenderer.invoke('add-channel', login),
  removeChannel: (login: string) => ipcRenderer.invoke('remove-channel', login),
  updateChannel: (login: string, patch: unknown) => ipcRenderer.invoke('update-channel', login, patch),
  moveChannel: (login: string, dir: number) => ipcRenderer.invoke('move-channel', login, dir),
  setOwn: (login: string | null) => ipcRenderer.invoke('set-own', login),
  updateSettings: (patch: unknown) => ipcRenderer.invoke('update-settings', patch),
  checkNow: () => ipcRenderer.invoke('check-now'),
  logout: () => ipcRenderer.invoke('logout'),
  openExternal: (url: string) => ipcRenderer.invoke('open-external', url),
  onShowGiveaways: (cb: () => void) => ipcRenderer.on('show-giveaways', () => cb()),
  joinGiveaway: (id: string, entry: string) => ipcRenderer.invoke('giveaway-join', id, entry),
  dismissGiveaway: (id: string) => ipcRenderer.invoke('giveaway-dismiss', id),
  getFollows: (force: boolean) => ipcRenderer.invoke('get-follows', force),
  importFollows: (logins: string[], opts: unknown) => ipcRenderer.invoke('import-follows', logins, opts),
  onToast: (cb: (msg: string) => void) => ipcRenderer.on('toast', (_e, m) => cb(m)),
  recSourceId: (wcId: number, login: string) => ipcRenderer.invoke('rec-source-id', wcId, login),
  recStart: (login: string, ext: string) => ipcRenderer.invoke('rec-start', login, ext),
  recChunk: (id: string, data: ArrayBuffer) => ipcRenderer.invoke('rec-chunk', id, data),
  recStop: (id: string) => ipcRenderer.invoke('rec-stop', id),
  recAllStopped: () => ipcRenderer.invoke('rec-all-stopped'),
  recDir: () => ipcRenderer.invoke('rec-dir'),
  recChooseDir: () => ipcRenderer.invoke('rec-choose-dir'),
  recOpenDir: () => ipcRenderer.invoke('rec-open-dir'),
  recShowFile: (file: string) => ipcRenderer.invoke('rec-show-file', file),
  onRecError: (cb: (id: string, msg: string) => void) => ipcRenderer.on('rec-error', (_e, id, m) => cb(id, m)),
  onStopAllRecordings: (cb: () => void) => ipcRenderer.on('stop-all-recordings', () => cb()),
  setStarred: (list: string[]) => ipcRenderer.invoke('set-starred', list),
  appVersion: () => ipcRenderer.invoke('app-version'),
  raidNotify: (source: string, target: string) => ipcRenderer.invoke('raid-notify', source, target),
  onRaid: (cb: (r: unknown) => void) => ipcRenderer.on('raid', (_e, r) => cb(r)),
  copyText: (text: string) => ipcRenderer.invoke('copy-text', text),
  getRewards: (login: string, force: boolean) => ipcRenderer.invoke('get-rewards', login, force),
  onShortcut: (cb: (name: string) => void) => ipcRenderer.on('shortcut', (_e, n) => cb(n)),
  setGiveawayRules: (rules: unknown) => ipcRenderer.invoke('set-giveaway-rules', rules),
  testGiveawayMessage: (text: string, privileged: boolean) => ipcRenderer.invoke('test-giveaway-message', text, privileged),
});
